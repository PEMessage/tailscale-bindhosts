# shellcheck shell=sh
# shellcheck disable=SC3043  # local is supported by Android mksh / busybox ash
# bindhosts layer: locate its active hosts file and rewrite our block.
#
# Sourced by lib/common.sh.

tsh_bh_installed() {
	[ -f "$BH_MODDIR/bindhosts.sh" ] && [ ! -f "$BH_MODDIR/remove" ]
}

tsh_bh_available() {
	tsh_bh_installed && [ ! -f "$BH_MODDIR/disable" ]
}

tsh_bh_mode() {
	sed -n 's/^operating_mode=//p' "$BH_MODDIR/mode.sh" 2>/dev/null | head -n 1
}

# Mirror bindhosts' operating_mode -> hosts file mapping.
tsh_bh_target() {
	local tsh_mode

	tsh_mode=$(tsh_bh_mode)
	case "$tsh_mode" in
		3) echo "$TSH_ADB/hosts" ;;
		4) echo "$TSH_ADB/hostsredirect/hosts" ;;
		7|8) echo /system/etc/hosts ;;
		*) echo "$BH_MODDIR/system/etc/hosts" ;;
	esac
}

# tsh_remove_block <target> <outfile>
#
# Copy <target> to <outfile>, dropping our marker block and any stale copy of
# the generated lines.  Both the entries we are about to write and the entries
# from the last successful apply are dropped: bindhosts may have rewritten the
# target and stripped our markers, so the previous snapshot is the only way to
# find rows for nodes that have since been removed or renamed.
tsh_remove_block() {
	local tsh_current tsh_applied

	[ -s "$TSH_ENTRIES" ] && tsh_current=$TSH_ENTRIES || tsh_current=""
	[ -s "$TSH_APPLIED" ] && tsh_applied=$TSH_APPLIED || tsh_applied=""

	tsh_awk -v mark_begin="$TSH_MARK_BEGIN" -v mark_end="$TSH_MARK_END" \
		-v entries="$tsh_current" -v applied="$tsh_applied" '
		BEGIN {
			if (entries != "")
				while ((getline line < entries) > 0)
					drop[line] = 1
			if (applied != "")
				while ((getline line < applied) > 0)
					drop[line] = 1
			if (entries != "")
				close(entries)
			if (applied != "")
				close(applied)
		}
		$0 == mark_begin {
			if (!skip) {
				skip = 1
				nb = 0
			}
			buf[++nb] = $0
			next
		}
		$0 == mark_end {
			if (skip) {
				skip = 0
				nb = 0
			}
			next
		}
		skip {
			buf[++nb] = $0
			next
		}
		($0 in drop) { next }
		{ print }
		END {
			# If the block was never closed, keep it instead of
			# dropping the rest of the hosts file.
			if (skip)
				for (i = 1; i <= nb; i++)
					print buf[i]
		}
	' "$1" > "$2"
}

# Print our marker block around the generated entries.
tsh_print_block() {
	printf '%s\n' "$TSH_MARK_BEGIN"
	cat "$TSH_ENTRIES"
	printf '%s\n' "$TSH_MARK_END"
}

# tsh_rewrite_target <target> <append:0|1>
#
# Replace <target> with a copy that has our old block removed and, when
# append=1, a fresh block appended.  Writing back with `cat >` keeps the
# target inode alive, which matters when bindhosts has bind-mounted it.
tsh_rewrite_target() {
	local tsh_target tsh_append tsh_new

	tsh_target=$1
	tsh_append=$2
	tsh_init
	tsh_new="$TSH_DIR/hosts.$$"

	if ! tsh_remove_block "$tsh_target" "$tsh_new"; then
		rm -f "$tsh_new"
		tsh_set_error "failed to rewrite $tsh_target"
		return 1
	fi

	if [ "$tsh_append" = "1" ]; then
		tsh_print_block >> "$tsh_new"
	fi

	if ! cat "$tsh_new" > "$tsh_target"; then
		rm -f "$tsh_new"
		tsh_set_error "failed to write $tsh_target"
		return 1
	fi
	rm -f "$tsh_new"
	return 0
}

# Remove the block, then append a fresh one.
tsh_inject() {
	local tsh_target

	tsh_target=$1
	if [ -z "$tsh_target" ] || [ ! -f "$tsh_target" ]; then
		tsh_set_error "hosts file not found: $tsh_target"
		return 1
	fi
	if [ ! -w "$tsh_target" ]; then
		tsh_set_error "hosts file is not writable: $tsh_target"
		return 1
	fi

	tsh_rewrite_target "$tsh_target" 1 || return 1

	chmod 644 "$tsh_target" 2>/dev/null
	chown 0:0 "$tsh_target" 2>/dev/null
	chcon --reference=/system/etc/hosts "$tsh_target" 2>/dev/null ||
		chcon --reference=/system "$tsh_target" 2>/dev/null
	return 0
}

# Remove only our block / generated lines (used by unapply).
# Returns 0 on success, 2 when the target does not exist, 3 when it is not
# writable, and 1 when the rewrite itself fails.
tsh_strip() {
	local tsh_target

	tsh_target=$1
	[ -n "$tsh_target" ] && [ -f "$tsh_target" ] || return 2
	[ -w "$tsh_target" ] || return 3

	tsh_rewrite_target "$tsh_target" 0
}

# Persist entries for bindhosts so its next update/reset keeps them.
tsh_write_bindhosts_custom() {
	local tsh_new

	tsh_init
	mkdir -p "$BH_PERSIST" 2>/dev/null
	tsh_new="$BH_CUSTOM.tmp.$$"
	{
		printf '# Generated by tailscale-bindhosts. Manual edits are overwritten.\n'
		tsh_print_block
	} > "$tsh_new" || {
		rm -f "$tsh_new"
		tsh_set_error "failed to write $BH_CUSTOM"
		return 1
	}

	mv -f "$tsh_new" "$BH_CUSTOM"
	chmod 644 "$BH_CUSTOM" 2>/dev/null
	return 0
}
